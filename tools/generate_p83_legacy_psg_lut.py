#!/usr/bin/env python3
"""Generate deterministic SN76489 -> GBA legacy APU translation tables.

Exact translations:
  * 10-bit SN tone period -> GBA pulse/wave frequency register at NTSC clock.
  * 4-bit SN attenuation -> GBA legacy envelope/wave amplitude.
  * channel-3 32-sample two-cycle square waveform for each attenuation.

Approximate experimental translation:
  * SN noise divider -> closest GBA channel-4 polynomial-clock setting.
    This matches rate only. The GB 7/15-bit LFSR cannot reproduce Sega's
    16-bit LFSR sequence, so this table is used only by P83 CGB4_APPROX.
"""
from pathlib import Path
import argparse, math

PSG_CLOCK=3_579_545
VOLUME=[15,12,10,8,6,5,4,3,2,2,1,1,1,0,0,0]

def tone_reg(period:int)->int:
    n=period & 0x3ff
    if n<2: n=1
    # Same round-to-nearest behavior as the old integer runtime conversion.
    delta=(4_194_304*n + PSG_CLOCK//2)//PSG_CLOCK
    delta=max(1,min(2047,delta))
    return (2048-delta)&0x7ff

def gb_noise_rate(rcode:int,shift:int)->float:
    divisor=0.5 if rcode==0 else float(rcode)
    return 524_288.0/(divisor*(2.0**(shift+1)))

def sn_noise_step_rate(period:int)->float:
    # Integrated Genesis PSG: clock/16 internal tick; the current exact software
    # core advances its 16-bit LFSR every second noise-counter expiration.
    return PSG_CLOCK/(32.0*max(1,period))

def noise_code(period:int)->int:
    target=sn_noise_step_rate(period)
    best=None
    for shift in range(16):
        for rcode in range(8):
            rate=gb_noise_rate(rcode,shift)
            err=abs(math.log(rate/target))
            item=(err,rcode,shift)
            if best is None or item<best: best=item
    _,rcode,shift=best
    return (shift<<4)|rcode

def generate(out:Path)->None:
    freq=[tone_reg(i) for i in range(1024)]
    noise=[noise_code(max(1,i)) for i in range(1024)]
    patterns=[]
    for amp in VOLUME:
        byte=(amp<<4)|amp
        hi=byte*0x01010101
        patterns.append((hi,0,hi,0))
    with out.open('w',newline='\n') as f:
        f.write('#ifndef MD2GBA_GBA_LEGACY_PSG_LUT_H\n#define MD2GBA_GBA_LEGACY_PSG_LUT_H\n#include <stdint.h>\n')
        f.write('/* Generated by tools/generate_p83_legacy_psg_lut.py. */\n')
        f.write('static const uint16_t md2gba_legacy_freq_ntsc[1024]={\n')
        for i in range(0,1024,16): f.write(' '+','.join(str(x) for x in freq[i:i+16])+',\n')
        f.write('};\n')
        f.write('static const uint8_t md2gba_legacy_volume_lut[16]={'+','.join(str(x) for x in VOLUME)+'};\n')
        f.write('static const uint32_t md2gba_legacy_wave_lut[16][4]={\n')
        for row in patterns: f.write(' {'+','.join(f'0x{x:08X}u' for x in row)+'},\n')
        f.write('};\n')
        f.write('/* Rate-only nearest GB noise clock. LFSR sequence is intentionally not claimed exact. */\n')
        f.write('static const uint8_t md2gba_legacy_noise_rate_lut[1024]={\n')
        for i in range(0,1024,16): f.write(' '+','.join(f'0x{x:02X}u' for x in noise[i:i+16])+',\n')
        f.write('};\n#endif\n')

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('output',nargs='?',default='runtime/generated/md2gba_gba_legacy_psg_lut.h')
    args=ap.parse_args()
    out=Path(args.output); out.parent.mkdir(parents=True,exist_ok=True); generate(out)

if __name__=='__main__': main()
