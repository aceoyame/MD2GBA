#!/usr/bin/env python3
"""Generate a title-agnostic native C AOT region from raw Genesis ROM bytes.

Input is a ROM plus either a JSON object containing `pcs`, or raw68k_cfg JSON
containing blocks/instructions. Timing/interrupt/audio services are supplied by
an external title profile through Md2GbaAotHooks, never hard-coded here.
"""
from __future__ import annotations
from pathlib import Path
import argparse, json, re, sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from raw68k_core import decode, with_bytes
from aot68k_codegen import emit_sem


def collect_pcs(obj):
    # Accept both a raw CFG report and higher-level expansion reports that
    # retain the final CFG under `cfg`. This keeps the emitter independent
    # of how control-flow discovery was obtained.
    if isinstance(obj, dict) and isinstance(obj.get('cfg'), dict):
        return collect_pcs(obj['cfg'])
    if isinstance(obj, dict) and isinstance(obj.get('pcs'), list):
        return sorted({int(x, 16) if isinstance(x, str) else int(x) for x in obj['pcs']})
    if isinstance(obj, dict) and isinstance(obj.get('blocks'), list):
        return sorted({int(i['address']) for b in obj['blocks'] for i in b.get('instructions', [])})
    if isinstance(obj, list):
        return sorted({int(x, 16) if isinstance(x, str) else int(x) for x in obj})
    raise ValueError('address report must contain pcs[] or raw68k_cfg blocks[]')


def ident(s):
    s = re.sub(r'[^A-Za-z0-9_]', '_', s)
    if not s or s[0].isdigit():
        s = 'r_' + s
    return s


def generate_region(rom: bytes, pcs: list[int], output: Path, symbol: str,
                    report_path: Path | None = None) -> dict:
    sym = ident(symbol)
    pcs = sorted(set(int(x) for x in pcs))
    decoded = []
    for pc in pcs:
        if pc < 0 or pc >= len(rom):
            raise ValueError(f'PC outside ROM: {pc:06X}')
        decoded.append(with_bytes(rom, decode(rom, pc)))

    cases = [f'case 0x{i["address"]:06X}u: {{ {emit_sem(i)} }} break;' for i in decoded]
    header_name = sym + '.h'
    text = f'''/* AUTO-GENERATED by tools/emit_aot_region.py. Do not edit. */
#include <stdint.h>
#include "md2gba_aot_region.h"
#include "{header_name}"

int {sym}_run(Md2Gba68k*c,Md2GbaBus*b,const Md2GbaAotHooks*hooks,uint32_t start,uint32_t stop,uint32_t max_steps){{
    uint32_t steps=0,t0=0,t1=0; if(start!=MD2GBA_AOT_RESUME_PC)c->pc=start&0xFFFFFFu;
    while(steps<max_steps){{
      int hr; uint32_t executed_pc=c->pc;
      if(steps && c->pc==stop)return MD2GBA_AOT_OK;
      steps++;
      switch(c->pc){{
''' + '\n'.join('        ' + x for x in cases) + '''
        default:
          if(hooks && hooks->handle_pc){
            hr=hooks->handle_pc(c,b,c->pc,hooks->user);
            if(hr>0) break;
            if(hr<0) return MD2GBA_AOT_HOOK_ERROR;
          }
          if(hooks && hooks->fallback_pc){
            hr=hooks->fallback_pc(c,b,c->pc,hooks->fallback_user);
            if(hr>0) break;
            if(hr<0) return MD2GBA_AOT_FALLBACK_ERROR;
          }
          return MD2GBA_AOT_MISSING_PC;
      }
      if(hooks && hooks->after_step){hr=hooks->after_step(c,b,executed_pc,steps,hooks->after_user);if(hr>0)return MD2GBA_AOT_YIELD;if(hr<0)return MD2GBA_AOT_EVENT_ERROR;}
    }
    return MD2GBA_AOT_STEP_LIMIT;
}
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text)
    guard = (sym + '_H').upper()
    output.with_name(header_name).write_text(f'''#ifndef {guard}
#define {guard}
#include <stdint.h>
#include "md2gba_aot_region.h"
int {sym}_run(Md2Gba68k*,Md2GbaBus*,const Md2GbaAotHooks*,uint32_t,uint32_t,uint32_t);
#endif
''')
    rep = {
        'symbol': sym,
        'instruction_count': len(decoded),
        'first_pc': f'{pcs[0]:06X}' if pcs else None,
        'last_pc': f'{pcs[-1]:06X}' if pcs else None,
    }
    if report_path:
        report_path.write_text(json.dumps(rep, indent=2))
    return rep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('rom', type=Path)
    ap.add_argument('addresses', type=Path)
    ap.add_argument('-o', '--output', type=Path, required=True)
    ap.add_argument('--symbol', default='md2gba_region')
    ap.add_argument('--report', type=Path)
    a = ap.parse_args()
    rom = a.rom.read_bytes()
    pcs = collect_pcs(json.loads(a.addresses.read_text()))
    rep = generate_region(rom, pcs, a.output, a.symbol, a.report)
    print(json.dumps(rep, indent=2))


if __name__ == '__main__':
    main()
